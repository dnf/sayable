"""Go locale emitter."""

from __future__ import annotations

from codegen.plural_rules import get_go_plural

HEADER = "// This file is auto-generated by codegen/generate.py — do not edit manually.\n"

# Plural category name mapping
_CAT_MAP = {
    "zero": "Zero", "one": "One", "two": "Two",
    "few": "Few", "many": "Many", "other": "Other",
}


def _quote(s: str) -> str:
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _unit_forms(unit: object) -> str:
    if isinstance(unit, str):
        return f"SimpleUnit({_quote(unit)})"
    cats = ["zero", "one", "two", "few", "many", "other"]
    pairs = []
    for cat in cats:
        if cat in unit:
            pairs.append(f"{_CAT_MAP[cat]}: {_quote(unit[cat])}")
    return "PluralUnit(map[PluralCategory]string{" + ", ".join(pairs) + "})"


def _stage_label(stage: object) -> str:
    if isinstance(stage, str):
        return f"S({_quote(stage)})"
    return f"G({_quote(stage['m'])}, {_quote(stage['f'])})"


def emit_locale(data: dict) -> str:
    code = data["code"]
    rule = data["pluralRule"]
    name = data["name"]
    uc = code.upper()

    lines = [HEADER, "package parenttime\n"]
    lines.append(f"// {uc} is the {name} locale.")
    lines.append(f"var {uc} = AgeLocale{{")

    # Code
    lines.append(f"\tCode: {_quote(code)},")

    # Plural
    plural = get_go_plural(rule)
    lines.append(f"\tPlural: {plural.lstrip()},")

    # Units
    lines.append("\tUnits: struct{ Day, Week, Month, Year UnitForms }{")
    for unit_name in ("day", "week", "month", "year"):
        cap = unit_name.capitalize()
        val = _unit_forms(data["units"][unit_name])
        lines.append(f"\t\t{cap}:{' ' * (6 - len(cap))}{val},")
    lines.append("\t},")

    # Simple fields
    lines.append(f"\tHalf:      {_quote(data['half'])},")
    lines.append(f"\tDelimiter: {_quote(data['delimiter'])},")
    lines.append(f"\tJustBorn:  {_quote(data['justBorn'])},")

    # Stages
    lines.append("\tStages: struct{ Newborn, Infant, Toddler, Child, Teenager, Adult StageLabel }{")
    for stage in ("newborn", "infant", "toddler", "child", "teenager", "adult"):
        cap = stage.capitalize()
        val = _stage_label(data["stages"][stage])
        lines.append(f"\t\t{cap}:{' ' * (9 - len(cap))}{val},")
    lines.append("\t},")

    # Short/compact
    for mode in ("short", "compact"):
        if mode in data:
            ovr = data[mode]
            cap = mode.capitalize()
            lines.append(f"\t{cap}: &CompactnessOverride{{")
            if "units" in ovr:
                for unit_name in ("day", "week", "month", "year"):
                    if unit_name in ovr["units"]:
                        ucap = unit_name.capitalize()
                        val = ovr["units"][unit_name]
                        if isinstance(val, str):
                            lines.append(f"\t\t{ucap}:{' ' * (6 - len(ucap))}&UnitForms{{Simple: {_quote(val)}}},")
                        else:
                            # Plural override — unusual but support it
                            lines.append(f"\t\t{ucap}:{' ' * (6 - len(ucap))}&{_unit_forms(val)},")
            if "delimiter" in ovr:
                lines.append(f'\t\tDelimiter: strPtr({_quote(ovr["delimiter"])}),')
            if "half" in ovr:
                lines.append(f'\t\tHalf:      strPtr({_quote(ovr["half"])}),')
            if "justBorn" in ovr:
                lines.append(f'\t\tJustBorn:  strPtr({_quote(ovr["justBorn"])}),')
            lines.append("\t},")

    lines.append("}")
    lines.append("")

    return "\n".join(lines)


def emit_barrel(all_locales: list[dict]) -> str | None:
    return None  # Go doesn't have barrel files


def output_path(code: str, root: str) -> str:
    import os
    return os.path.join(root, "go", f"locale_{code}.go")


def barrel_path(root: str) -> str | None:
    return None
