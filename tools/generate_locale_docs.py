#!/usr/bin/env python3
"""Generate the locale docs from locales/*.json and the Python implementations.

Writes:
    docs/locales/<code>.md   one page per locale: real output from all four
                             libraries (age, date, duration, time), and the
                             locale's open review notes
    docs/locales/README.md   every review note across all locales, for linguists
    locales/README.md        the index linguists start from

Each library renders its own section (`python -m codegen.docgen --sections`
in that library's directory, which formats examples with its Python
implementation), so every library's examples are generated and checked the
same way.

Usage:
    python3 tools/generate_locale_docs.py           # write
    python3 tools/generate_locale_docs.py --check   # exit 1 if anything is stale
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCALES_DIR = os.path.join(ROOT, "locales")
DOCS_DIR = os.path.join(ROOT, "docs", "locales")
INDEX_PATH = os.path.join(LOCALES_DIR, "README.md")
REVIEW_PATH = os.path.join(DOCS_DIR, "README.md")
LIBRARIES = ("age", "date", "duration", "time")
GENERATED_NOTE = "<!-- Generated by tools/generate_locale_docs.py — do not edit by hand -->"

# The categories each plural rule can return (age and duration use them).
PLURAL_CATEGORIES = {
    "other_only": "other",
    "one_other": "one, other",
    "one_other_zero_one": "one, other",
    "cs_sk": "one, few, other",
    "lt": "one, few, other",
    "ro": "one, few, other",
    "slavic_bcs": "one, few, other",
    "pl": "one, few, many",
    "ru_uk": "one, few, many",
    "sl": "one, two, few, other",
    "ar": "zero, one, two, few, many, other",
    "lv": "zero, one, other",
    "he": "one, two, other",
    "mk": "one, other",
    "cy": "zero, one, two, few, many, other",
    "gv": "one, two, few, other",
    "gd": "one, two, few, other",
    "ga": "one, two, few, many, other",
    "mt": "one, two, few, many, other",
    "br": "one, two, few, many, other",
    "kw": "zero, one, two, few, many, other",
    "shi": "one, few, other",
    "tzm": "one, other",
}


def load_locales() -> list[dict]:
    locales = []
    for fname in sorted(os.listdir(LOCALES_DIR)):
        if fname.endswith(".json"):
            with open(os.path.join(LOCALES_DIR, fname), encoding="utf-8") as f:
                locales.append(json.load(f))
    return locales


def library_sections(library: str) -> dict[str, str]:
    """Every locale's section for one library, keyed by locale code."""
    result = subprocess.run(
        [sys.executable, "-m", "codegen.docgen", "--sections"],
        cwd=os.path.join(ROOT, library), capture_output=True, text=True, check=False,
    )
    if result.returncode != 0:
        sys.exit(f"error: {library} docgen failed:\n{result.stderr}")
    return json.loads(result.stdout)


# Review notes are listed least confident first.
CONFIDENCE_ORDER = {"low": 0, "medium": 1}
NO_NOTE_CAVEAT = ("A locale with no review notes has not necessarily been checked by a native "
                  "speaker; notes mark the places we already know are uncertain.")


def review_notes(locale: dict) -> list[dict]:
    return sorted(locale.get("review", []), key=lambda r: CONFIDENCE_ORDER.get(r["confidence"], 2))


def review_section(locale: dict) -> list[str]:
    notes = review_notes(locale)
    if not notes:
        return []
    lines = ["## Needs review", "",
             "These parts of the data are uncertain. If you speak the language, please check the",
             f"examples below against them and fix [{locale['code']}.json](../../locales/{locale['code']}.json),",
             "deleting the note from its `review` list once the data is right.", ""]
    for note in notes:
        lines.append(f"- **`{note['section']}`** ({note['confidence']} confidence): {note['note']}")
    return lines + [""]


def locale_page(locale: dict, sections: dict[str, dict[str, str]]) -> str:
    code = locale["code"]
    lines = [GENERATED_NOTE, "", f"# {locale['name']} ({code})", "",
             f"[Edit source](../../locales/{code}.json)", ""]
    rule = locale.get("pluralRule")
    if rule:
        lines += [f"Plural rule: `{rule}` (categories: {PLURAL_CATEGORIES.get(rule, rule)})", ""]
    lines += review_section(locale)
    for library in LIBRARIES:
        lines += [f"## {library.capitalize()}", "", sections[library][code].rstrip("\n"), ""]
    return "\n".join(lines)


def index_page(locales: list[dict]) -> str:
    lines = [
        GENERATED_NOTE, "",
        "# Locales",
        "",
        "Each locale is one JSON file: the shared `code`, `name` and `pluralRule`, then a",
        "section for each library (`age`, `date`, `duration`, `time`). It is the single",
        "source of truth for that language in every programming language.",
        "",
        "To change a locale, edit its JSON file, then run `just generate locales`. That",
        "regenerates the locale code in every implementation and the example pages in",
        "[docs/locales/](../docs/locales/). Never edit generated files by hand. See",
        "[adding a locale](../docs/adding-a-locale.md) for the field reference.",
        "",
        "Places where the data is known to be uncertain are listed in",
        "[docs/locales/README.md](../docs/locales/README.md), the best place for a",
        "linguist to start.",
        "",
        f"## All {len(locales)} locales",
        "",
        "| Language | Code | Plural rule | Source | Examples | Review |",
        "| -------- | ---- | ----------- | ------ | -------- | ------ |",
    ]
    for loc in sorted(locales, key=lambda d: d["name"].lower()):
        code = loc["code"]
        notes = review_notes(loc)
        review = f"[{notes[0]['confidence']}](../docs/locales/{code}.md#needs-review)" if notes else "—"
        lines.append(f"| {loc['name']} | `{code}` | `{loc.get('pluralRule', '—')}` "
                     f"| [{code}.json]({code}.json) | [examples](../docs/locales/{code}.md) | {review} |")
    lines.append("")
    return "\n".join(lines)


def review_index_page(locales: list[dict]) -> str:
    """Every open review note, least confident first, so linguists can pick one up."""
    rows = [(note, loc) for loc in locales for note in review_notes(loc)]
    rows.sort(key=lambda r: (CONFIDENCE_ORDER.get(r[0]["confidence"], 2), r[1]["name"].lower()))
    counts = {c: sum(1 for note, _ in rows if note["confidence"] == c) for c in CONFIDENCE_ORDER}
    lines = [
        GENERATED_NOTE, "",
        "# Locales that need review",
        "",
        "Parts of the locale data we are not confident in, collected from the `review` list",
        "in each [locales/<code>.json](../../locales/). If you speak one of these languages,",
        "open its examples page, check the output against the note, and fix the JSON. Once",
        "the data is right, delete the note from its `review` list and run",
        "`just generate locales`.",
        "",
        NO_NOTE_CAVEAT,
        "",
        f"{len(rows)} notes: {counts['low']} low confidence, {counts['medium']} medium confidence.",
        "",
        "| Language | Code | Section | Confidence | What to check |",
        "| -------- | ---- | ------- | ---------- | ------------- |",
    ]
    for note, loc in rows:
        code = loc["code"]
        text = note["note"].replace("|", "\\|")
        lines.append(f"| [{loc['name']}]({code}.md#needs-review) | `{code}` | `{note['section']}` "
                     f"| {note['confidence']} | {text} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if any file is out of date")
    args = parser.parse_args()

    locales = load_locales()
    sections = {library: library_sections(library) for library in LIBRARIES}
    wanted = {os.path.join(DOCS_DIR, f"{loc['code']}.md"): locale_page(loc, sections) for loc in locales}
    wanted[INDEX_PATH] = index_page(locales)
    wanted[REVIEW_PATH] = review_index_page(locales)

    stale = [path for path, content in wanted.items()
             if not os.path.exists(path) or open(path, encoding="utf-8").read() != content]
    extra = [os.path.join(DOCS_DIR, f) for f in sorted(os.listdir(DOCS_DIR))
             if os.path.join(DOCS_DIR, f) not in wanted] if os.path.isdir(DOCS_DIR) else []

    if args.check:
        for path in stale + extra:
            print(f"out of date: {os.path.relpath(path, ROOT)}")
        if stale or extra:
            print("Run `just generate locales` to update.", file=sys.stderr)
            return 1
        print(f"Locale docs are up to date ({len(locales)} locales).")
        return 0

    os.makedirs(DOCS_DIR, exist_ok=True)
    for path in stale:
        with open(path, "w", encoding="utf-8") as f:
            f.write(wanted[path])
    for path in extra:
        os.remove(path)
    print(f"Wrote {len(stale)} file(s), removed {len(extra)} stale page(s), {len(locales)} locales.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
