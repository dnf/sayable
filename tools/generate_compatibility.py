#!/usr/bin/env python3
"""Generate Compatibility.md from component impl/ directories."""

from __future__ import annotations

import os
import sys

_COMPONENTS = ["age", "date", "duration", "time"]

_DISPLAY_NAMES: dict[str, str] = {
    "cobol": "COBOL",
    "cpp": "C++",
    "csharp": "C#",
    "fsharp": "F#",
    "ocaml": "OCaml",
    "php": "PHP",
    "typescript": "TypeScript",
}

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_OUTPUT = os.path.join(_ROOT, "Compatibility.md")


def _display_name(dirname: str) -> str:
    return _DISPLAY_NAMES.get(dirname, dirname.capitalize())


def _discover() -> dict[str, set[str]]:
    """Return {component: set of directory names} for each component."""
    result: dict[str, set[str]] = {}
    for comp in _COMPONENTS:
        impl_dir = os.path.join(_ROOT, comp, "impl")
        if os.path.isdir(impl_dir):
            result[comp] = {
                e for e in os.listdir(impl_dir)
                if os.path.isdir(os.path.join(impl_dir, e))
            }
        else:
            result[comp] = set()
    return result


def _generate() -> str:
    """Return the full Compatibility.md content."""
    data = _discover()

    all_langs = set()
    for langs in data.values():
        all_langs |= langs
    sorted_langs = sorted(all_langs, key=lambda d: _display_name(d).lower())

    lines: list[str] = []
    lines.append(
        "<!-- Generated by tools/generate_compatibility.py — do not edit by hand -->\n"
    )
    lines.append("# Compatibility\n")
    lines.append("\n")
    lines.append(
        "Which languages are available for each Sayable library.\n"
    )
    lines.append("\n")
    lines.append("<table>\n")
    lines.append("<tr>\n")
    lines.append("  <th>Language</th>\n")
    for comp in _COMPONENTS:
        lines.append(f"  <th>{comp}</th>\n")
    lines.append("</tr>\n")

    for dirname in sorted_langs:
        name = _display_name(dirname)
        lines.append("<tr>\n")
        lines.append(f"  <td>{name}</td>\n")
        for comp in _COMPONENTS:
            if dirname in data[comp]:
                lines.append(
                    f'  <td><a href="{comp}/impl/{dirname}/">✅</a></td>\n'
                )
            else:
                lines.append("  <td>❌</td>\n")
        lines.append("</tr>\n")

    lines.append("</table>\n")

    return "".join(lines)


def main() -> None:
    check = "--check" in sys.argv

    content = _generate()

    if check:
        if os.path.exists(_OUTPUT):
            with open(_OUTPUT, encoding="utf-8") as f:
                existing = f.read()
            if existing == content:
                print("Compatibility.md is up to date.")
                return
            print("Compatibility.md is out of date.")
            print("Run 'python tools/generate_compatibility.py' to update.")
            sys.exit(1)
        else:
            print("Compatibility.md does not exist.")
            print("Run 'python tools/generate_compatibility.py' to generate it.")
            sys.exit(1)

    with open(_OUTPUT, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Generated {os.path.relpath(_OUTPUT, _ROOT)}")


if __name__ == "__main__":
    main()
